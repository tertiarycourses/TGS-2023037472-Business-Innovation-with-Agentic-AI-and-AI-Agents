#!/usr/bin/env python3
"""Write the four activity boards (data_bi.CANVASES) to the bcm web app as js/templates.js.
Single source: edit data_bi.py, re-run this, commit the bcm repo.
Usage: python3 export_bcm_templates.py [path-to-bcm-repo]   (default ~/projects/edtools/bcm)"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import data_bi as B

repo = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/projects/edtools/bcm")
import re
# v61 (owner, 28 Nov 2026): the board draws each box's number (1-9) in a circle. A title that starts with a
# number must start with THAT number; the old plan-step prefixes (1,1,2,3,3,4,5,5,5) read as wrong numbering.
for c in B.CANVASES:
    for i, b in enumerate(c["blocks"]):
        m = re.match(r"(\d+)\s*·", b["title"])
        assert not m or int(m.group(1)) == i + 1, f"{c['key']} box {i + 1}: title '{b['title']}' starts with another number"
out = []
for c in sorted(B.CANVASES, key=lambda c: c["num"]):
    out.append(dict(key=c["key"], num=c["num"], topic=c["topic"], lo=c["lo"], codes=c["codes"], layout=c["layout"],
                    title=c["title"], short=c["short"], pitch=c["pitch"], musePrompt=c["muse_prompt"], evidence=c["evidence"], discuss=c["discuss"],
                    minutes=c["minutes"],
                    blocks=[dict(id=b["id"], num=i + 1, title=b["title"], prompt=b["prompt"], questions=b["questions"],
                                 example=[dict(title=t, description=d) for t, d in b["example"]])
                            for i, b in enumerate(c["blocks"])]))
js = ("// GENERATED by the course build (export_bcm_templates.py from data_bi.py) - do not edit by hand.\n"
      f"// Course: WSQ Business Innovation with Agentic AI and AI Agents (TGS-2023037472).\n"
      f"export const EXAMPLE_COMPANY = {json.dumps(B.EXAMPLE_CO)};\n"
      f"export const EXAMPLE_BLURB = {json.dumps(B.EXAMPLE_BLURB)};\n"
      f"export const TEMPLATES = {json.dumps(out, indent=1, ensure_ascii=False)};\n"
      "export const TEMPLATE_BY_KEY = Object.fromEntries(TEMPLATES.map(t => [t.key, t]));\n")
os.makedirs(os.path.join(repo, "js"), exist_ok=True)
open(os.path.join(repo, "js", "templates.js"), "w", encoding="utf-8").write(js)
print("wrote", os.path.join(repo, "js", "templates.js"), len(out), "templates")
